def _load_canonical_summaries():
    """Map {(book, article_number): arabic_reference_summary} from canonical data.

    `legal_rule_summary_ar` is sourced from this map, never hardcoded, so the
    layer stays byte-identical to the canonical article Arabic summaries.
    """
    canon = {}
    for book, path in SRC.items():
        with open(path, "r", encoding="utf-8") as fh:
            for art in json.load(fh)["articles"]:
                canon[(book, art["article_number"])] = art["arabic_reference_summary"]
    return canon


CANON = _load_canonical_summaries()


